#!/bin/bash
# own Pine scripts -> js/own.js; stamp the version into index.html (?v=<hash>) and versi.txt
set -e
cd "$(dirname "$0")"
python3 - <<'PY'
import json,pathlib
names=[('p_breakout','Breakout Liemyo','BreakoutLiemyo')]
o=[dict(id=i,name=n,code=pathlib.Path('pine/'+f+'.pine').read_text()) for i,n,f in names]
pathlib.Path('js/own.js').write_text('/* generated by build.sh from pine/ */\nwindow.AC_OWN = '+json.dumps(o,ensure_ascii=False)+';\n')
PY
for f in js/*.js; do node --check "$f"; done
H=$(cat index.src.html js/*.js css/*.css | shasum | cut -c1-12)
sed "s/%%VERSI%%/$H/g" index.src.html > index.html
echo "$H" > versi.txt
echo "versi $H"
